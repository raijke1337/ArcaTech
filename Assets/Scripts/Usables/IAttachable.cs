namespace Arcatech.Usables
{
    /// <summary>
    /// Обратимый жизненный цикл компонентов применения. Attach - предмет экипирован: подписаться на
    /// события, зарегистрироваться в триггерах. Detach - предмет снят: отписаться и освободить ресурсы.
    /// Можно вызывать по кругу (снять -> надеть). Оба вызова идемпотентны.
    /// Раньше подписки создавались в конструкторе и были необратимы, из-за чего неэкипированные
    /// предметы получали хиты общей зоны ближнего боя, а оставшиеся - теряли подписки.
    /// </summary>
    public interface IAttachable
    {
        void Attach();
        void Detach();
    }
}
